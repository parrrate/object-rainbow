use static_assertions::const_assert_eq;

pub fn derive_length(source: u64) -> u32 {
    const SIZE: u32 = u64::BITS;
    const HEAD_SIZE: u32 = 4;
    const TAIL_SIZE: u32 = SIZE - HEAD_SIZE;
    const TAIL_MASK: u64 = (1 << TAIL_SIZE) - 1;
    const BASE_BITS: u32 = 17;
    const MAX_BITS: u32 = BASE_BITS + ((1 << HEAD_SIZE) - 1) - 1;
    const MAX_GARBAGE: u32 = TAIL_SIZE - BASE_BITS;
    const_assert_eq!(MAX_BITS, 31);
    let head = (source >> TAIL_SIZE) as u32;
    let tail = source & TAIL_MASK;
    let garbage = MAX_GARBAGE - head.saturating_sub(1);
    let extra = (tail >> garbage) as u32;
    let main = if head == 0 {
        0
    } else {
        1 << (BASE_BITS - 1 + head)
    };
    main | extra
}

#[test]
#[expect(clippy::unusual_byte_groupings)]
fn cases() {
    let f = derive_length;
    assert_eq!(
        f(0b_0000_00000000000000000_1111111111111111111111111111111111111111111),
        0b_00000000000000000,
    );
    assert_eq!(
        f(0b_0000_11111111111111111_0000000000000000000000000000000000000000000),
        0b_11111111111111111,
    );
    assert_eq!(
        f(0b_0001_00000000000000000_1111111111111111111111111111111111111111111),
        0b_100000000000000000,
    );
    assert_eq!(
        f(0b_0001_11111111111111111_0000000000000000000000000000000000000000000),
        0b_111111111111111111,
    );
    assert_eq!(
        f(0b_0010_000000000000000000_111111111111111111111111111111111111111111),
        0b_1000000000000000000,
    );
    assert_eq!(
        f(0b_0010_111111111111111111_000000000000000000000000000000000000000000),
        0b_1111111111111111111,
    );
    assert_eq!(
        f(0b_0100_00000000000000000000_1111111111111111111111111111111111111111),
        0b_100000000000000000000,
    );
    assert_eq!(
        f(0b_0100_11111111111111111111_0000000000000000000000000000000000000000),
        0b_111111111111111111111,
    );
    assert_eq!(
        f(0b_1000_000000000000000000000000_111111111111111111111111111111111111),
        0b_1000000000000000000000000,
    );
    assert_eq!(
        f(0b_1000_111111111111111111111111_000000000000000000000000000000000000),
        0b_1111111111111111111111111,
    );
    assert_eq!(
        f(0b_1111_0000000000000000000000000000000_11111111111111111111111111111),
        0b_10000000000000000000000000000000,
    );
    assert_eq!(
        f(0b_1111_1111111111111111111111111111111_00000000000000000000000000000),
        0b_11111111111111111111111111111111,
    );
}
